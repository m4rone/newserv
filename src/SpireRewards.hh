// One offer: what a menu slot gives when it is taken
struct SpireRewardOffer {
  SpireRewardKind kind = SpireRewardKind::NONE;
  SpireRewardTier tier = SpireRewardTier::NORMAL;
  uint8_t w = 0;
  uint32_t room_index = 0;
  uint8_t slot = 0;
  uint8_t entry_id = 0;
  std::string line; // the weapon's line (Nieuwe lijn: the new line)
  std::string from_line; // the line the player held
  SpireMagBytes item{}; // the weapon's data1 (kind WEAPON and NEW_LINE)
  std::string item_name; // "Brand +3", "VISK-235W", "Gladius +12 Berserk"
  uint16_t food_levels = 0; // MAG_FOOD
  uint8_t tech = 0xFF; // DISK: the technique (0-18) and its level (1-30); the item is 03 02 level-1 00 tech
  uint8_t tech_level = 0;
  uint32_t mst_required = 0; // DISK: the MST the client asks for it
  SpireRewardItemInfo info; // the weapon's requirements
  std::string label; // the menu text: tier word + name ("EPIC Musashi", "RARE Mag food +10", "RARE Foie Lv8")
};
// What a DISK offer needs to know of the run copy (the bridge fills it; the pure part chooses):
//   known      per technique 0xFF, or the level (0-based) the copy knows
//   class_max  per technique 0xFF, or the highest level (0-based) the class can learn: the item parameter table's
//              MaxTechLevels, the same value newserv holds a used disk against (Items.cc), so no disk is ever above it
//   mst        the copy's MST with the worn units, without the mag (as a weapon's MST requirement reads it)
//   mst_cap    the class's highest MST (the client caps the total there); 0 = not known, no cap
//   mind_room  the MIND levels rule B's mag can carry: 200 less the POW and DEX the reward weapon asks
//   mind_now   the MIND levels of the run mag the copy wears (0 without one)
//   mind_plan  the MIND levels the run mag is planned to have at this point of the run: its step row, or the floor of
//              the bought start levels when that is higher (0 without a ledger)
// and of its draw entry:
//   line_tech  the technique of the disk the entry names itself (a line that was a fixed disk, "Foie": its own item
//              03 02 level-1 00 tech), 0xFF for a line without one ("Disk"). The offer keeps that technique while the
//              copy can still grow in it (Marck, 16 Nov 2026: "the reward must simply be a spell a force can use"),
//              whether or not Sega drops it in the room; else any technique Sega drops there, as "Disk"
//   extra_levels  what a drawn curse on the pick adds to the disk (spire_reward_curse_disk_levels), as far as the
//              class's highest level and the copy's MST go
struct SpireRewardDiskState {
  std::array<uint8_t, SPIRE_TECH_COUNT> known;
  std::array<uint8_t, SPIRE_TECH_COUNT> class_max;
  uint32_t mst = 0;
  uint32_t mst_cap = 0;
  uint16_t mind_room = 200;
  uint16_t mind_now = 0;
  uint16_t mind_plan = 0;
  uint8_t line_tech = 0xFF;
  uint8_t extra_levels = 0;
  SpireRewardDiskState() {
    this->known.fill(0xFF);
    this->class_max.fill(0xFF);
  }
};
// The levels a drawn curse adds to a technique disk (pso-roguelike rewards.py curse_extra, which adds them to a disk
// of the quest's own): Cursed Chest (code 1, R12_DISK_LEVELS) and Glass (3, GLASS_DISK_LEVELS) two each; Jellen Mark
// (2) pays in grind, on a weapon only.
constexpr uint8_t spire_reward_curse_disk_levels(uint32_t curse) {
  return ((curse == 1) || (curse == 3)) ? 2 : 0;
}
// The MST a DISK offer of a tier may count on (design/mechanics/force-spells.md par. 2): the copy's MST and two per MIND
// level of the mag it wears, or of the mag's plan with the tier's tilt (tier_mind) when that is more, within mind_room.
// So a spell follows the strength of the copy (a difficulty rung and bought start levels raise it by themselves), and
// a higher tier reaches further above it without the mag going all MIND for one disk.
constexpr uint32_t spire_reward_disk_budget(const SpireRewardDiskState& state, uint16_t tier_mind) {
  uint32_t mind = std::max<uint32_t>(state.mind_now, static_cast<uint32_t>(state.mind_plan) + tier_mind);
  return state.mst + (2 * std::min<uint32_t>(mind, state.mind_room));
}
// The level of a DISK offer for one technique, 0 for none. The highest level whose MST the budget meets (at most
// mst_cap), at most the class's highest; for a technique the copy knows at least two levels above what it knows
// (pso-roguelike design/kracht-voorbij-normaal.md par. 4: "disk +2 levels"; one level when that is the class's
// highest) and for any other at least level 1, so a disk always teaches something; state.extra_levels on top, within
// the class's highest. Then down, never to what the copy knows, until the copy can meet the MST the client asks: the
// requirement at most mst_cap, and the MIND it takes within mind_room.
uint8_t spire_reward_disk_level(const SpireRewardTech& tech, uint32_t budget, uint8_t known, uint8_t class_max,
    const SpireRewardDiskState& state);
// rnd(n): uniform 0..n-1. held: data1 of the weapon the player holds (nullptr: none, the class's first line). The tier is
// given (spire_reward_tier_for_roll). Throws when the class has no line for it (not in the grid). disk: the run copy
// for a DISK offer (required for that kind; it throws without, and when no technique has a level to give). rung: the
// difficulty rung of the run's quest (0 Normal - 3 Ultimate), which lifts a weapon's W (spire_reward_w) and moves the
// column of the grid that says which techniques a disk may be (rung_disk_columns).
SpireRewardOffer spire_reward_offer(const SpireRewardTable& table, SpireRewardKind kind, uint8_t char_class,
    const uint8_t* held, uint32_t room_index, SpireRewardTier tier, const std::function<uint32_t(uint32_t)>& rnd,
    const SpireRewardDiskState* disk = nullptr, uint8_t rung = 0);
// The weapon of a cell as data1: code, grind (at most the weapon's MaxGrind), the special, Hit
SpireMagBytes spire_reward_weapon_bytes(const SpireRewardTable& table, const SpireRewardCell& cell, uint8_t special);

// Rule B's need of a weapon for the run copy's stats (design par. 3: +2 ATP per POW, +2 MST per MIND, DEX by the ATA
// model): the levels each stat must have, rounded up
SpireMagNeed spire_reward_mag_need(const SpireRewardItemInfo& info, uint32_t atp, uint32_t ata, uint32_t mst,
    SpireAtaModel model);
// Rule B's need with a reward disk in the run: the weapon's POW and DEX always stand, and the disks' MIND takes what
// they leave of the mag's 200 levels. So a disk never drops the weapon's POW and DEX, and a reward weapon can be worn
// when it is given (Marck's rule for every reward) even when it and the run's disks ask more than 200 together: the
// disks are learned by then, their MIND gives way. The weapon's own MIND (a cane) stands.
constexpr SpireMagNeed spire_reward_need_with_disk(const SpireMagNeed& weapon, uint16_t disk_mind) {
  uint32_t asked = static_cast<uint32_t>(weapon.pow) + weapon.dex;
  uint16_t room = (asked < 200) ? static_cast<uint16_t>(200 - asked) : 0;
  return SpireMagNeed{weapon.pow, weapon.dex, std::max<uint16_t>(weapon.mind, std::min<uint16_t>(disk_mind, room))};
}
// Whether stats plus a mag (the same assumed rates) meet a weapon's requirement under a model (the log's measurement)
bool spire_reward_meets(const SpireRewardItemInfo& info, uint32_t atp, uint32_t ata, uint32_t mst, const SpireMagBytes* mag,
    SpireAtaModel model);

// What the equipped units add to the stats a weapon's requirement is held against (Marck, 16 Nov 2026: "frame with 4
// slots and items in it count toward the ability to equip weapons"): ATP (unit stat 0), MST (stat 1), both from stat 8
// (God/Ability). ATA units are left out: whether their amount is in table units or tenths is not settled
// (ItemParameterTable.hh says tenths, the table holds 3 for Marksman/Arm), and leaving them out only makes rule B's
// mag carry a little more.
struct SpireUnitBonus {
  uint32_t atp = 0;
  uint32_t mst = 0;
};
constexpr void spire_reward_unit_bonus_add(SpireUnitBonus& bonus, uint16_t stat, uint16_t amount) {
  if ((stat == 0) || (stat == 8)) {
    bonus.atp += amount;
  }
  if ((stat == 1) || (stat == 8)) {
    bonus.mst += amount;
  }
}
// The slot (0-3; equip slot 9 + n) a new unit goes into: the first of the frame's slots (its data1[5], at most 4) that
// no equipped unit holds (occupied: bit n set = slot n taken); nullopt when the frame has none free
constexpr std::optional<uint8_t> spire_reward_free_unit_slot(uint8_t occupied, uint8_t frame_slots) {
  for (uint8_t n = 0; (n < 4) && (n < frame_slots); n++) {
    if (!(occupied & (1 << n))) {
      return n;
    }
  }
  return std::nullopt;
}

// What the player reads when a reward unit stays in the pack (no % and no < >: a ticker line). review r1 B4: "no free
// slot" covers a full frame and a frame without slots (the kit frame at r143 = 0, which equip_item makes)
constexpr const char* SPIRE_REWARD_UNIT_NO_SLOT_TEXT = "No free unit slot: the unit is in your Item Pack.";
constexpr const char* SPIRE_REWARD_UNIT_NO_FRAME_TEXT = "No frame worn: the unit is in your Item Pack.";

// When SpireEquipItem goes out for a reward weapon. The game holds a weapon's requirement also when the server equips
// it (Marck, 16 Nov 2026), so a weapon that rule B's mag must carry (mag_due) waits until that mag is on the client
// (the ledger's boost_due cleared by its RESULT 1) and equipped in newserv's copy. polls counts the waits so far,
// polls_since_landed those since the mag's RESULT 1. A mag that never comes (pack full, the run over) or that the
// game leaves unequipped ends the wait: the equip then goes as it did before, and the journal says so.
constexpr auto SPIRE_REWARD_EQUIP_POLL_DELAY = std::chrono::milliseconds(1000);
constexpr uint32_t SPIRE_REWARD_MAG_WAIT_POLLS = 1200; // 20 min: a busy lock leaves the mag owed for the next room clear
constexpr uint32_t SPIRE_REWARD_MAG_EQUIP_POLLS = 8; // SPIRE_RUN_MAG_EQUIP_SENDS sends, each with its check delay
enum class SpireRewardEquipGate {
  GO, // no mag owed, or the mag is on and equipped
  WAIT,
  GO_WITHOUT_MAG, // the wait ran out
};
constexpr SpireRewardEquipGate spire_reward_equip_gate(bool mag_due, bool has_ledger, bool boost_due, bool mag_equipped,
    uint32_t polls, uint32_t polls_since_landed) {
  if (!mag_due || !has_ledger) {
    return SpireRewardEquipGate::GO;
  }
  if (boost_due) {
    return (polls < SPIRE_REWARD_MAG_WAIT_POLLS) ? SpireRewardEquipGate::WAIT : SpireRewardEquipGate::GO_WITHOUT_MAG;
  }
  if (mag_equipped) {
    return SpireRewardEquipGate::GO;
  }
  return (polls_since_landed < SPIRE_REWARD_MAG_EQUIP_POLLS) ? SpireRewardEquipGate::WAIT
                                                             : SpireRewardEquipGate::GO_WITHOUT_MAG;
}
