// Fase 1 part A (pso-roguelike new-features/roguelike/design/beloningen-per-klasse.md, kracht-voorbij-normaal.md par.
// 4-5): the reward types Wapen (a weapon of the line the player holds), Nieuwe lijn (a weapon of another line of the
// class) and Mag-voer (levels on the mag's main stat), each in four tiers. The server picks the concrete item at the
// draw ('Q', SpireDraw) and names it in the reward line; at the pick the quest asks 'Z' sub 6 and creates what the
// server answers in r20-r31; the server then equips it (SpireEquipItem) after the run mag followed rule B.
//
// The grid is system/spire-rewards.json, generated by pso-roguelike quests/spire/make_spire_rewards.py from the design
// grid beloningen-per-klasse.json (never edited by hand). The pure parts live here, for the static tests; the 'Z'
// handler, the offers per client and the log lines in SpireFlagBridge.cc.

constexpr const char* SPIRE_REWARDS_FILE = "system/spire-rewards.json";

// 'Z' sub 6 REWARD: 'Z' << 24 | 6 << 16 | board slot << 8 | entry id (pool index + 1). Answer: r20-r31 the item's
// data1 when bit 0 of r41 is set, r41 = SPIRE_REWARD_ANSWER_TAG | flags, then r248 = 'DONE'.
// 'Z' sub 7 REWARD_RESULT: 'Z' << 24 | 7 << 16 | created (1: item_create2 made it, 0: FFFFFFFF). No answer.
constexpr uint8_t SPIRE_RUN_MAG_REWARD = 6;
constexpr uint8_t SPIRE_RUN_MAG_REWARD_RESULT = 7;
// bits 16-23 of the answer are 0x80: a run mag answer has 0 there (SpireMag.hh spire_run_mag_answer), so a late mag
// answer is never read as a reward answer
constexpr uint32_t SPIRE_REWARD_ANSWER_TAG = SPIRE_RUN_MAG_TAG | (0x80u << 16);
constexpr uint32_t SPIRE_REWARD_ITEM = 1; // r20-r31 hold the item to create
constexpr uint32_t SPIRE_REWARD_MAG_FOLLOWS = 2; // the quest asks the run mag next (sub 1), which answers rule B

// The ATA model (design par. 3): which ATA the client holds against a weapon's ATA requirement. One key, AtaModel, in
// SPIRE_REWARDS_FILE, read by the reward grid and by SpireDrops (spire_drops_weapon_fit).
//   TABLE         the table ATA (character data) >= requirement; a DEX level is 5 table units
//   SCREEN_WEAPON 60 + table/10 + the weapon's own ATA >= requirement; a DEX level is 0.5
//   SCREEN_BARE   60 + table/10 >= requirement (refuted by the journal, kept for comparison)
//   SAFE          TABLE and SCREEN_WEAPON both (the grid's model; the default)
enum class SpireAtaModel { TABLE = 0, SCREEN_WEAPON, SCREEN_BARE, SAFE };
SpireAtaModel spire_ata_model_for_name(const std::string& name); // throws on an unknown name
const char* spire_ata_model_name(SpireAtaModel model);
// The DEX levels a mag must give so the table ATA `ata` meets `required` for a weapon with own ATA `weapon_ata`
uint32_t spire_ata_dex_needed(SpireAtaModel model, uint32_t ata, uint32_t weapon_ata, uint32_t required);
// The model SPIRE_REWARDS_FILE names; SAFE when the file or its key is missing or unreadable. Reads the file at most once
// per change of its time stamp.
SpireAtaModel spire_ata_model_configured();

enum class SpireRewardTier : uint8_t { NORMAL = 0, RARE, EPIC, LEGENDARY };
const char* spire_reward_tier_name(SpireRewardTier tier); // "Normal" ... "Legendary" (the grid's keys)
// The label word the menu line starts with (KV par. 4): NORMAL, RARE, EPIC, LEGEND
const char* spire_reward_tier_label(SpireRewardTier tier);
// The ticker colour of the tier (KV par. 4: Normal white, Rare blue, Epic yellow, Legendary yellow with its word)
const char* spire_reward_tier_color(SpireRewardTier tier);

// Part B adds UNIT (Kracht, KV par. 4): a unit for one of the frame's slots, by the class's archetype and the tier, and
// DISK (Schijf): a technique disk of Sega's level for the room and the tier, which the run copy can learn (below).
enum class SpireRewardKind : uint8_t { NONE = 0, WEAPON = 1, NEW_LINE = 2, MAG_FOOD = 3, DISK = 4, UNIT = 5 };
const char* spire_reward_kind_name(SpireRewardKind kind);
// Whether a draw table's srv value names a kind this server gives; any other value reads as "no server reward"
// (SpireDraw.cc), so the pick answers the entry's own item
constexpr bool spire_reward_kind_known(int64_t srv) {
  return (srv >= 1) && (srv <= 5);
}

struct SpireRewardItemInfo {
  std::string name;
  uint32_t stars = 0;
  uint32_t atp = 0; // requirements
  uint32_t ata = 0;
  uint32_t mst = 0;
  uint32_t weapon_ata = 0; // the weapon's own ATA
  uint32_t max_grind = 0;
};
struct SpireRewardSpecial {
  uint8_t id = 0;
  std::string name;
};
// A unit of the grid (01 03 xx): its stat and amount as the item parameter table has them (ItemParameterTable.hh Unit)
struct SpireRewardUnit {
  std::string name;
  uint32_t stars = 0;
  uint16_t stat = 0;
  uint16_t amount = 0;
};
// A technique of the grid (part B, the disk): the MST the GC client asks before it lets a disk be used is
// Base + Step * (level - 1), held against the total MST with the mag and the units (pso-roguelike
// new-features/roguelike/research/schijf-mst-eis.md; read from the client image, every technique)
constexpr size_t SPIRE_TECH_COUNT = 19;
struct SpireRewardTech {
  std::string name;
  uint16_t base = 0;
  uint16_t step = 0;
};
constexpr uint32_t spire_reward_disk_mst(const SpireRewardTech& tech, uint8_t level) { // level 1-30
  return tech.base + (static_cast<uint32_t>(tech.step) * (level ? (level - 1) : 0));
}
// The MIND levels a mag must have for a requirement on a copy with this MST (+2 MST per MIND level, rounded up)
constexpr uint16_t spire_reward_disk_mind(uint32_t mst_required, uint32_t mst) {
  return (mst_required > mst) ? static_cast<uint16_t>(std::min<uint32_t>((mst_required - mst + 1) / 2, 0xFFFF)) : 0;
}
struct SpireRewardCell {
  uint32_t code = 0; // data1[0-2], big-endian as the grid writes it (000101 = Brand)
  std::string name;
  uint8_t grind = 0;
  uint8_t hit = 0; // Hit % (attribute 5), 0 = none
  std::vector<SpireRewardSpecial> specials; // one is chosen at the draw; empty = none
  bool fallback = false; // no Sega rare fits: the Normal weapon with a special a star higher
  std::array<uint16_t, 4> grid_mag{}; // POW, DEX, MIND, level the grid computed (bonus 0, the grid's run level)
};
struct SpireRewardWeaponLevel {
  uint32_t run_level = 0;
  uint32_t run_atp = 0, run_ata = 0, run_mst = 0; // the grid's run copy stats
  std::array<SpireRewardCell, 4> tiers;
};
struct SpireRewardLine {
  uint32_t kit = 0;
  std::map<uint8_t, SpireRewardWeaponLevel> w; // W2-W6
};
struct SpireRewardClass {
  std::string name;
  std::string archetype;
  std::vector<std::string> line_order; // sorted, Saber first: front() is the line without a known weapon held
  std::map<std::string, SpireRewardLine> lines;
};
struct SpireRewardTable {
  bool enabled = false;
  SpireAtaModel ata_model = SpireAtaModel::SAFE;
  std::string source;
  uint32_t rare_width = 30, epic_base = 3, epic_per_room = 2, epic_elite = 15, legendary_from_trede = 2,
           legendary_room = 5, legendary_room_bonus = 2, legendary_elite = 3, cap = 60;
  uint8_t trede1_room = 4, trede2_room = 8;
  std::array<uint16_t, 4> mag_food{};
  std::map<uint32_t, uint8_t> room_w; // room index -> W
  std::map<uint8_t, std::string> line_groups; // data1[1] of a plain weapon -> line
  std::map<uint32_t, std::string> line_of; // a weapon code -> line
  std::map<uint32_t, SpireRewardItemInfo> items;
  std::map<uint8_t, SpireRewardClass> classes; // by the character class (0-11)
  // part B: the units by code (0103xx), and per archetype ("HU", "RA", "FO") and tier the codes a UNIT reward draws
  // from. Both empty when the file has no Units (a part A file): a UNIT entry then gives its own item.
  std::map<uint32_t, SpireRewardUnit> units;
  std::map<std::string, std::array<std::vector<uint32_t>, 4>> unit_tiers;
  // part B, the disk: the techniques by id (0 Foie - 18 Megid) and per room index (1 = the first room of the episode)
  // the level of Sega's disk per technique and tier (0: Sega drops none there). Empty when the file has no Disks: a
  // DISK entry then gives its own item.
  std::array<SpireRewardTech, SPIRE_TECH_COUNT> techs;
  std::map<uint32_t, std::array<std::array<uint8_t, 4>, SPIRE_TECH_COUNT>> disk_levels;
};
